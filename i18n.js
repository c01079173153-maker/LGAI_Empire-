function applyTranslation(lang) {
  const t = TRANSLATIONS[lang];
  if (!t) return;
  currentLang = lang;
  localStorage.setItem('lgai_lang', lang);

  // Apply RTL for Arabic
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';

  Object.entries(I18N_MAP).forEach(([selector, key]) => {
    document.querySelectorAll(selector).forEach(el => {
      if (t[key] !== undefined) el.textContent = t[key];
    });
  });

  // Update language button label
  const btn = document.getElementById('langBtnLabel');
  if (btn) btn.textContent = `${t.flag} ${t.lang}`;

  // Close dropdown
  const dropdown = document.getElementById('langDropdown');
  if (dropdown) dropdown.classList.remove('open');
}

function buildLangSwitcher() {
  const nav = document.querySelector('.nav-inner');
  if (!nav) return;

  const wrapper = document.createElement('div');
  wrapper.className = 'lang-switcher';
  wrapper.innerHTML = `
    <button class="lang-btn" id="langBtn" onclick="toggleLangDropdown()">
      <span id="langBtnLabel">🇺🇸 English</span>
      <span class="lang-chevron">▾</span>
    </button>
    <div class="lang-dropdown" id="langDropdown">
      ${Object.entries(TRANSLATIONS).map(([code, t]) =>
        `<button class="lang-option" onclick="applyTranslation('${code}')">${t.flag} ${t.lang}</button>`
      ).join('')}
    </div>
  `;
  nav.appendChild(wrapper);
}

function toggleLangDropdown() {
  document.getElementById('langDropdown').classList.toggle('open');
}

// Close on outside click
document.addEventListener('click', (e) => {
  const sw = document.querySelector('.lang-switcher');
  if (sw && !sw.contains(e.target)) {
    const dd = document.getElementById('langDropdown');
    if (dd) dd.classList.remove('open');
  }
});

// Init
document.addEventListener('DOMContentLoaded', () => {
  buildLangSwitcher();
  applyTranslation(currentLang);
});
